--  WHY LUA: Hyprland >=0.55 deprecated hyprlang, and `main` (development toward
--  0.57) has already deleted src/config/legacy entirely. 0.56.2 still falls back
--  to hyprland.conf when no hyprland.lua exists, so the old config kept working
--  — but that fallback disappears in 0.57. This file being present means the Lua
