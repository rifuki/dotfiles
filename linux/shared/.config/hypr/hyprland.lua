--  ROLLBACK: rename this file (e.g. hyprland.lua.off). Hyprland then finds no Lua
--  config and reads hyprland.conf again, which is still on disk beside it.
--
--  Each require() gets its own Lua scope, so a runtime error in one module does
--  not abort the others. Loading a module that does not exist IS fatal, however
--  — require() throws in the caller's scope.
--
